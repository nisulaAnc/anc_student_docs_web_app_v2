// Function to get all product code mappings (for debugging)
function getAllProductCodeMappings(): array {
    try {
        $rows = sheetRead(SHEET_PRODUCTS, 'I2:K500');
    } catch (Exception $e) {
        return [];
    }
    
    $mappings = [];
    foreach ($rows as $r) {
        $major = isset($r[0]) ? trim((string)$r[0]) : '';
        $degree = isset($r[1]) ? trim((string)$r[1]) : '';
        $productCode = isset($r[2]) ? trim((string)$r[2]) : '';
        
        if ($major && $degree && $productCode) {
            $mappings[$major . ' - ' . $degree] = $productCode;
        }
    }
    return $mappings;
}
